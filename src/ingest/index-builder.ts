import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { compareCodeUnits } from "../core/compare.js";
import { toPosixRelative } from "../core/paths.js";
import type { ResolvedPaths } from "../core/paths.js";
import { listPageFiles, loadPages } from "../wiki/parse-page.js";
import type { Page } from "../wiki/parse-page.js";

export const INDEX_TYPE_ORDER: readonly string[] = ["person", "team", "project", "risk", "decision", "glossary", "source"];

function encodePath(p: string): string {
  return p
    .split("/")
    .map((s) => encodeURIComponent(s).replace(/\(/g, "%28").replace(/\)/g, "%29"))
    .join("/");
}

function line(page: Page): string {
  const fm = page.frontmatter;
  const title = (fm.title ?? page.path.split("/").pop()!.replace(/\.md$/, "")).replace(/[[\]]/g, (c) => `\\${c}`);
  const summary = fm.summary === null ? "" : fm.summary.replace(/\s+/g, " ").trim();
  return `- [${title}](pages/${encodePath(page.path)})${summary === "" ? "" : ` — ${summary}`}`;
}

function archivedLine(n: number): string {
  return n === 1
    ? "_1 archived page — search it with `wikeeper search --archive`._"
    : `_${n} archived pages — search them with \`wikeeper search --archive\`._`;
}

export function buildIndex(pages: readonly Page[], opts?: { archived?: number }): string {
  const head = "# Wiki index\n\n";
  const archived = opts?.archived ?? 0;
  const extra = archived > 0 ? `${archivedLine(archived)}\n\n` : "";
  if (pages.length === 0) return archived > 0 ? `${head}_No pages yet._\n\n${archivedLine(archived)}\n` : `${head}_No pages yet._\n`;
  const groups = new Map<string, Page[]>();
  for (const p of pages) {
    const key = p.frontmatter.type ?? "untyped";
    const list = groups.get(key);
    if (list === undefined) groups.set(key, [p]);
    else list.push(p);
  }
  const known = INDEX_TYPE_ORDER.filter((t) => groups.has(t));
  const other = [...groups.keys()]
    .filter((t) => t !== "untyped" && !INDEX_TYPE_ORDER.includes(t))
    .sort(compareCodeUnits);
  const order = [...known, ...other, ...(groups.has("untyped") ? ["untyped"] : [])];
  const sections = order.map((t) => {
    const list = [...groups.get(t)!].sort((a, b) => compareCodeUnits(a.path, b.path));
    return `## ${t}\n\n${list.map(line).join("\n")}\n`;
  });
  return `${head}_Generated by \`wikeeper ingest finish\` or \`wikeeper index rebuild\` from page frontmatter. Do not edit._\n\n${extra}${sections.join("\n")}`;
}

export async function writeIndex(
  paths: ResolvedPaths,
): Promise<{ file: string; pages: number; archived: number; changed: boolean; errors: Array<{ path: string; message: string }> }> {
  const pages = await loadPages(paths.pagesDir);
  const archived = (await listPageFiles(paths.archiveDir)).length;
  const text = buildIndex(pages, { archived });
  let current: string | null = null;
  try {
    current = await readFile(paths.indexFile, "utf8");
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
  }
  const changed = current !== text;
  if (changed) {
    await mkdir(path.dirname(paths.indexFile), { recursive: true });
    await writeFile(paths.indexFile, text);
  }
  const errors = pages.flatMap((p) =>
    p.errors.map((e) => ({ path: p.path, message: e.line === null ? e.message : `line ${e.line}: ${e.message}` })),
  );
  return { file: toPosixRelative(paths.root, paths.indexFile), pages: pages.length, archived, changed, errors };
}
